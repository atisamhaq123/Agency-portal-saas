import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const baseUrl = process.env.TEST_URL || 'http://localhost:3000';
const errors=[];
try {
  const page=await browser.newPage({ viewport:{width:1440,height:1050}, deviceScaleFactor:1 });
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(baseUrl);
  await page.getByRole('heading',{name:/Good things ahead/}).waitFor();
  await mkdir('artifacts',{recursive:true});
  await page.screenshot({path:'artifacts/desktop.png',fullPage:true});
  await page.getByRole('button',{name:'New project',exact:true}).click();
  await page.getByLabel('Project name').fill('Browser test project');
  await page.getByLabel('Client / business').fill('Test Studio');
  await page.getByLabel('Client email').fill('test@client.demo');
  await page.getByLabel('Due date').fill('2026-12-01');
  await page.getByRole('button',{name:'Create project',exact:true}).click();
  await page.getByRole('button',{name:'Projects',exact:true}).click();
  await page.getByRole('textbox',{name:'Search projects'}).fill('Browser test');
  await page.getByRole('button',{name:/Browser test project.*Test Studio/}).click();
  await page.getByLabel('Progress',{exact:true}).fill('40');
  await page.getByRole('button',{name:'Save changes',exact:true}).click();
  await page.getByText('40% complete',{exact:true}).waitFor();
  await page.locator('input[type=file]').setInputFiles({name:'test-deliverable.pdf',mimeType:'application/pdf',buffer:Buffer.from('Demo metadata upload')});
  await page.getByRole('button',{name:'Approve deliverable',exact:true}).click();
  await page.getByText('Approved',{exact:true}).waitFor();
  await page.reload();
  await page.getByRole('button',{name:'Projects',exact:true}).click();
  await page.getByRole('textbox',{name:'Search projects'}).fill('Browser test');
  assert.equal(await page.locator('.project-card').count(),1);
  await page.getByRole('button',{name:/Studio North Agency workspace/}).click();
  await page.getByRole('button',{name:'Coastal Collective',exact:true}).click();
  await page.getByRole('textbox',{name:'Search projects'}).fill('');
  assert.equal(await page.locator('.project-card').count(),1);
  assert.equal(await page.getByRole('button',{name:/Coastal stories/}).count(),1);
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await page.getByRole('button',{name:'Reset demo',exact:true}).click();
  await page.getByRole('button',{name:'Switch to client view',exact:true}).click();
  assert.equal(await page.locator('.project-card').count(),1);
  assert.equal(await page.getByRole('button',{name:'New project',exact:true}).count(),0);
  await page.getByRole('button',{name:'Approvals',exact:false}).first().click();
  const review=page.locator('.delivery').first();
  await review.getByRole('textbox').fill('Please make the logo a little larger.');
  await review.getByRole('button',{name:'Request changes'}).click();
  await page.getByText('Changes requested',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await page.getByRole('button',{name:'Reset demo',exact:true}).click();
  await page.getByRole('button',{name:'Plans & billing',exact:true}).click();
  await page.getByRole('button',{name:'Choose Starter',exact:false}).click();
  await page.getByRole('status').filter({hasText:/sign in to your connected account/}).waitFor();
  for(const view of ['Overview','Projects','Approvals','Files','Clients','Plans & billing','Settings']) {
    await page.setViewportSize({width:390,height:844});
    await page.getByRole('button',{name:view,exact:view!=='Approvals'}).first().click();
    const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
    assert.equal(overflow,false,`No horizontal overflow in ${view}`);
  }
  await page.getByRole('button',{name:'Overview',exact:true}).click();
  const dismiss = page.getByRole('button',{name:'Dismiss message',exact:true});
  if (await dismiss.count()) await dismiss.click();
  await page.screenshot({path:'artifacts/mobile.png',fullPage:true});
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await page.getByLabel('Email address').fill('demo@example.com');
  await page.getByLabel('Password',{exact:true}).fill('password123');
  await page.getByRole('dialog').getByRole('button',{name:'Sign in',exact:true}).click();
  await page.getByText(/Live login needs Supabase configuration/).waitFor();
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('dialog').count(),0);
  assert.deepEqual(errors,[],'No browser runtime errors');
  const invalidWebhook=await page.request.post(`${baseUrl}/api/stripe/webhook`,{data:'{}'});
  assert.equal(invalidWebhook.status(),503);
  console.log('Browser checks passed: project creation, progress, upload metadata, approval, persistence, workspace isolation, client view, feedback, billing demo, seven mobile views, login, modal keyboard dismissal, no runtime errors.');
} finally { await browser.close(); }
