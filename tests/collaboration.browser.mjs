import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const base = process.env.TEST_URL || 'http://localhost:3000';
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(`${base}/portal?demo=1`);
  await page.getByRole('button', { name: 'New project', exact: true }).click();
  await page.getByLabel('Project name').fill('Collaboration test project');
  await page.getByLabel('Client / business').fill('Test Client');
  await page.getByLabel('Client email').fill('jordan@acme.demo');
  await page.getByLabel('Due date').fill('2026-12-01');
  await page.getByRole('button', { name: 'Create project', exact: true }).click();
  await page.getByRole('button', { name: /Collaboration test project.*Test Client/ }).click();
  await page.getByLabel('Milestone title', { exact: true }).fill('Creative direction');
  await page.getByLabel('Milestone due date').fill('2026-11-15');
  await page.getByRole('button', { name: 'Add milestone', exact: true }).click();
  await page.getByRole('checkbox', { name: /Creative direction/ }).check();
  await page.getByText('1 / 1 complete', { exact: true }).waitFor();
  await page.getByLabel('Project message', { exact: true }).fill('The first direction is ready for feedback.');
  await page.getByRole('button', { name: 'Send message', exact: true }).click();
  await page.getByText('The first direction is ready for feedback.', { exact: true }).waitFor();
  await page.reload();
  await page.getByRole('button', { name: /Collaboration test project.*Test Client/ }).click();
  assert.equal(await page.getByRole('checkbox', { name: /Creative direction/ }).isChecked(), true);
  await page.getByText('The first direction is ready for feedback.', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('button', { name: 'Switch to client view', exact: true }).click();
  await page.getByRole('button', { name: /Collaboration test project.*Test Client/ }).click();
  assert.equal(await page.getByRole('checkbox', { name: /Creative direction/ }).isDisabled(), true);
  assert.equal(await page.getByRole('button', { name: 'Add milestone', exact: true }).count(), 0);
  assert.equal(await page.getByRole('button', { name: /Remove milestone/ }).count(), 0);
  await page.getByLabel('Project message', { exact: true }).fill('Thanks. I will review this today.');
  await page.getByRole('button', { name: 'Send message', exact: true }).click();
  await page.getByText('Thanks. I will review this today.', { exact: true }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'Collaboration fits mobile');
  await page.screenshot({ path: 'artifacts/collaboration-mobile.png', fullPage: true });
  assert.deepEqual(errors, []);
  console.log('Collaboration checks passed: owner milestones, completion, conversation, persistence, client read-only milestones, client reply, and mobile layout.');
} finally { await browser.close(); }
