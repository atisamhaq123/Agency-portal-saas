import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const base = process.env.TEST_URL || 'http://localhost:3000';
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(`${base}/portal?demo=1`);
  await page.getByRole('button', { name: 'Notifications, 1 unread', exact: true }).click();
  const inbox = page.getByRole('region', { name: 'Notification inbox', exact: true });
  await inbox.getByText('Deliverable approved', { exact: true }).waitFor();
  assert.equal(await inbox.getByText('New file ready for review', { exact: true }).count(), 0);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await inbox.getByRole('button', { name: 'Mark all read', exact: true }).click();
  await inbox.getByText('0 unread', { exact: true }).waitFor();
  await page.keyboard.press('Escape');
  assert.equal(await inbox.count(), 0);
  await page.reload();
  await page.getByRole('button', { name: 'Notifications', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('button', { name: 'Switch to client view', exact: true }).click();
  await page.getByRole('button', { name: 'Notifications, 1 unread', exact: true }).click();
  await inbox.getByText('New file ready for review', { exact: true }).waitFor();
  assert.equal(await inbox.getByText('Deliverable approved', { exact: true }).count(), 0);
  await inbox.getByRole('button', { name: /New file ready for review.*Visual identity/ }).click();
  await page.locator('.detail').waitFor();
  await page.getByRole('button', { name: 'Notifications', exact: true }).waitFor();
  await page.getByLabel('Project message', { exact: true }).fill('Can we review the direction tomorrow?');
  await page.getByRole('button', { name: 'Send message', exact: true }).click();
  await page.getByText('Can we review the direction tomorrow?', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('button', { name: 'Switch to owner view', exact: true }).click();
  await page.getByRole('button', { name: 'Notifications, 1 unread', exact: true }).click();
  await inbox.getByText('New project message', { exact: true }).waitFor();
  await page.screenshot({ path: 'artifacts/inbox-mobile.png' });
  await inbox.getByRole('button', { name: 'Mark read: New project message', exact: true }).click();
  await inbox.getByText('0 unread', { exact: true }).waitFor();
  assert.deepEqual(errors, []);
  console.log('Inbox checks passed: unread badge, recipient filtering, mark all, mark one, persistence, Escape, project navigation, message notifications, and mobile layout.');
} finally { await browser.close(); }
